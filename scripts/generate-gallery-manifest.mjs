import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesRoot = join(projectRoot, 'public', 'images');
const outputFile = join(projectRoot, 'src', 'gallery-images.js');
const categories = ['commercial', 'residential', 'solar'];
const imageExtensions = /\.(avif|gif|jpe?g|png|webp)$/i;

const galleries = {};

for (const category of categories) {
  const categoryDirectory = join(imagesRoot, category);
  const files = (await readdir(categoryDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && imageExtensions.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));

  galleries[category] = files;
}

const manifest = `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit manually.\nexport const galleryImages = ${JSON.stringify(galleries, null, 2)};\n`;
await writeFile(outputFile, manifest, 'utf8');

const summary = categories.map((category) => `${category}: ${galleries[category].length}`).join(', ');
console.log(`Gallery manifest generated (${summary})`);
